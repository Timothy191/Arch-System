'use strict';

/**
 * Documentation governance: required artifacts, generated component catalog,
 * completeness scoring, and change-to-docs enforcement.
 */

const fs = require('node:fs');
const path = require('node:path');

const { isAgentContentPath } = require('./constants.cjs');
const { discoverComponents } = require('./component-registry.cjs');
const { hasSection, readText, relative, toPosix, writeText } = require('./util.cjs');

function escapeCell(value) {
  const text = String(value || '—')
    .replace(/\|/g, '\\|')
    .replace(/\r?\n/g, ' ')
    .trim();
  if (text.length <= 140) return text;
  const clipped = text.slice(0, 140);
  const boundary = clipped.lastIndexOf(' ');
  return `${(boundary > 40 ? clipped.slice(0, boundary) : clipped).trimEnd()}…`;
}

function table(headers, rows) {
  if (rows.length === 0) return '_None discovered._\n';
  const header = `| ${headers.join(' | ')} |`;
  const divider = `| ${headers.map(() => '---').join(' | ')} |`;
  const body = rows.map((row) => `| ${row.join(' | ')} |`).join('\n');
  return `${header}\n${divider}\n${body}\n`;
}

function documentedSurfaceCount(components) {
  const entries = [
    ...components.agents.map((entry) => entry.description),
    ...components.registry.map((entry) => entry.description),
    ...components.skills.map((entry) => entry.description),
    ...components.rules.map((entry) => entry.description),
    ...components.schemas.map((entry) => entry.description),
    ...components.hooks.scripts.map((entry) => entry.script),
    ...components.directives.map((entry) => entry.description),
    ...components.qoderAgents.map((entry) => entry.description),
    ...components.memory.map((entry) => entry.path),
    ...Object.values(components.coordination).map((entry) => entry.path),
  ];
  const documented = entries.filter((entry) => String(entry || '').trim().length > 0).length;
  return { total: entries.length, documented };
}

function generateCatalog(components) {
  const agents = [...components.agents].sort((a, b) => a.name.localeCompare(b.name));
  const registry = [...components.registry].sort((a, b) => a.name.localeCompare(b.name));
  const skills = [...components.skills].sort((a, b) =>
    `${a.root}/${a.name}`.localeCompare(`${b.root}/${b.name}`)
  );
  const rules = [...components.rules].sort((a, b) => a.path.localeCompare(b.path));
  const schemas = [...components.schemas].sort((a, b) => a.name.localeCompare(b.name));
  const coverage = documentedSurfaceCount(components);

  const lines = [];
  lines.push('# Agentic Engineer Component Catalog');
  lines.push('');
  lines.push('> Generated by `pnpm agent:engineer:docs --write`. Do not edit by hand.');
  lines.push('> Regenerate after any agent-content change so documentation stays in sync.');
  lines.push('');
  lines.push('## Coverage');
  lines.push('');
  lines.push(
    `- Documented agent-content surfaces: **${coverage.documented}/${coverage.total}** ` +
      `(${coverage.total ? Math.round((coverage.documented / coverage.total) * 1000) / 10 : 100}%).`
  );
  lines.push(`- Agent definitions: ${agents.length}`);
  lines.push(`- Registry cards: ${registry.length}`);
  lines.push(`- Skills: ${skills.length}`);
  lines.push(`- Rules: ${rules.length}`);
  lines.push(`- A2A schemas: ${schemas.length}`);
  lines.push(`- Hook scripts: ${components.hooks.scripts.length}`);
  lines.push('');
  lines.push('## Agents');
  lines.push('');
  lines.push(
    table(
      ['Agent', 'Definition', 'Registry card', 'Description'],
      agents.map((agent) => [
        `\`${agent.name}\``,
        `\`${agent.path}\``,
        registry.some((entry) => entry.name === agent.name)
          ? `\`.agents/a2a/registry/${agent.name}.json\``
          : 'MISSING',
        escapeCell(agent.description),
      ])
    ).trimEnd()
  );
  lines.push('');
  lines.push('## Skills');
  lines.push('');
  lines.push(
    table(
      ['Skill', 'Root', 'Path', 'Description'],
      skills.map((skill) => [
        `\`${skill.name}\``,
        `\`${skill.root}\``,
        `\`${skill.path}\``,
        escapeCell(skill.description),
      ])
    ).trimEnd()
  );
  lines.push('');
  lines.push('## Rules');
  lines.push('');
  lines.push(
    table(
      ['Rule', 'Root', 'Path', 'Description'],
      rules.map((rule) => [
        `\`${rule.name}\``,
        `\`${rule.root}\``,
        `\`${rule.path}\``,
        escapeCell(rule.description),
      ])
    ).trimEnd()
  );
  lines.push('');
  lines.push('## A2A Schemas');
  lines.push('');
  lines.push(
    table(
      ['Schema', 'Path', 'Title'],
      schemas.map((schema) => [
        `\`${schema.name}\``,
        `\`${schema.path}\``,
        escapeCell(schema.description),
      ])
    ).trimEnd()
  );
  lines.push('');
  lines.push('## Hook Scripts');
  lines.push('');
  lines.push(
    table(
      ['Script', 'Events', 'Referenced'],
      components.hooks.scripts.map((script) => [
        `\`${script.script}\``,
        script.events.length > 0 ? script.events.join(', ') : '—',
        script.events.length > 0 ? 'yes' : 'no',
      ])
    ).trimEnd()
  );
  lines.push('');
  lines.push('## Root Directives');
  lines.push('');
  lines.push(
    table(
      ['Directive', 'Present', 'Symlink', 'Purpose'],
      components.directives.map((directive) => [
        `\`${directive.path}\``,
        directive.exists ? 'yes' : 'no',
        directive.symlink ? `→ ${directive.linkTarget}` : 'no',
        escapeCell(directive.description),
      ])
    ).trimEnd()
  );
  lines.push('');
  lines.push('## Coordination Surfaces');
  lines.push('');
  lines.push(
    table(
      ['Surface', 'Path', 'Status'],
      [
        [
          'Whiteboard claims',
          `\`${components.coordination.claims.path}\``,
          components.coordination.claims.valid ? 'valid' : 'invalid',
        ],
        [
          'Whiteboard canvas',
          `\`${components.coordination.canvas.path}\``,
          components.coordination.canvas.nonEmpty ? 'valid' : 'empty',
        ],
        [
          'Intercom log',
          `\`${components.coordination.intercom.path}\``,
          `${components.coordination.intercom.records} record(s)`,
        ],
        [
          'A2A event log',
          `\`${components.coordination.eventLog.path}\``,
          `${components.coordination.eventLog.records} record(s)`,
        ],
      ]
    ).trimEnd()
  );
  lines.push('');
  lines.push('## Related Artifacts');
  lines.push('');
  lines.push('- `docs/agents/agentic-engineer/SPEC.md` — technical specification');
  lines.push('- `docs/agents/agentic-engineer/USAGE.md` — usage guide');
  lines.push('- `docs/agents/agentic-engineer/INTEGRATION.md` — integration notes');
  lines.push('- `docs/agents/agentic-engineer/RUNBOOK.md` — operational runbook');
  lines.push(
    '- `documentation/03-audit-reports/agentic-engineer-health.md` — generated health report'
  );
  lines.push('');
  return lines.join('\n');
}

function writeCatalog(root, config) {
  const components = discoverComponents(root);
  const catalogPath = path.join(root, config.documentation.catalog);
  const content = generateCatalog(components);
  writeText(catalogPath, content);
  return { path: config.documentation.catalog, content, components };
}

function evaluateRequiredDocs(root, config) {
  const results = [];
  for (const required of config.documentation.required || []) {
    const filePath = path.join(root, required.path);
    const content = readText(filePath);
    const missingSections = (required.sections || []).filter(
      (section) => !hasSection(content, section)
    );
    const failures = [];
    if (!content) failures.push(`${required.path} is missing or empty`);
    else if (content.trim().length < 200) failures.push(`${required.path} is too short`);
    for (const section of missingSections) {
      failures.push(`${required.path} is missing required section "${section}"`);
    }
    results.push({
      id: required.id,
      type: required.type,
      path: required.path,
      ok: failures.length === 0,
      failures,
    });
  }
  return results;
}

function evaluateChangeSync(changedFiles, config) {
  const normalized = (changedFiles || []).map(toPosix);
  const agentChanges = normalized.filter((file) => isAgentContentPath(file, config));
  const docsRoot = config.documentation.root;
  const catalogDir = path.posix.dirname(config.documentation.catalog);
  const docChanges = normalized.filter(
    (file) =>
      file === docsRoot || file.startsWith(`${docsRoot}/`) || file.startsWith(`${catalogDir}/`)
  );
  const ok = agentChanges.length === 0 || docChanges.length > 0;
  return {
    id: 'change-sync',
    type: 'documentation-sync',
    ok,
    agentChanges,
    docChanges,
    failures:
      ok || agentChanges.length === 0
        ? []
        : [
            `${agentChanges.length} agent-content file(s) changed without a documentation update ` +
              `under ${docsRoot}/ or ${catalogDir}/`,
          ],
  };
}

function evaluateDocs({ root, config, changedFiles = null }) {
  const required = evaluateRequiredDocs(root, config);
  const catalogPath = path.join(root, config.documentation.catalog);
  const expectedCatalog = generateCatalog(discoverComponents(root));
  const actualCatalog = readText(catalogPath);
  const catalogCheck = {
    id: 'catalog',
    type: 'component-catalog',
    path: config.documentation.catalog,
    ok: actualCatalog === expectedCatalog,
    failures:
      actualCatalog === expectedCatalog
        ? []
        : [`${config.documentation.catalog} is stale — run "pnpm agent:engineer:docs --write"`],
  };
  const checks = [...required, catalogCheck];
  if (Array.isArray(changedFiles)) checks.push(evaluateChangeSync(changedFiles, config));
  const passed = checks.filter((entry) => entry.ok).length;
  const failures = checks.flatMap((entry) =>
    entry.failures.map((message) => ({ id: entry.id, message }))
  );
  return {
    ok: passed === checks.length,
    completeness: Math.round((passed / checks.length) * 1000) / 10,
    total: checks.length,
    passed,
    checks,
    failures,
    required,
    catalogUpToDate: catalogCheck.ok,
  };
}

function listDocumentationChanges(root, config) {
  const docsRoot = path.join(root, config.documentation.root);
  const files = [];
  const walk = (dir) => {
    if (!fs.existsSync(dir)) return;
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      const full = path.join(dir, entry.name);
      if (entry.isDirectory()) walk(full);
      else files.push(relative(root, full));
    }
  };
  walk(docsRoot);
  return files;
}

module.exports = {
  evaluateDocs,
  generateCatalog,
  listDocumentationChanges,
  writeCatalog,
};
