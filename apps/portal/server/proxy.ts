import { cacheEvictL1ByPrefix, cacheGet, cacheSet } from '@repo/redis/cache';
import {
  type EmployeeRecord,
  readSession,
  revokeSession,
  touchSession,
  writeSession,
} from '@repo/redis/session';
import { createMiddlewareClient } from '@repo/supabase/middleware';
import { type NextRequest, NextResponse } from 'next/server';
import { recordJobExecution } from '@/lib/observability/simple-metrics';

type MiddlewareClient = Awaited<ReturnType<typeof createMiddlewareClient>>;

/**
 * Copies cookies from a Supabase middleware response onto a target
 * NextResponse. Used so refreshed session tokens survive a redirect
 * generated by the proxy.
 */
function copyCookies(source: NextResponse | undefined, target: NextResponse): void {
  if (!source?.cookies) return;
  for (const cookie of source.cookies.getAll()) {
    target.cookies.set(cookie.name, cookie.value, {
      path: cookie.path,
      domain: cookie.domain,
      secure: cookie.secure,
      httpOnly: cookie.httpOnly,
      sameSite: cookie.sameSite,
      expires: cookie.expires,
      maxAge: cookie.maxAge,
    });
  }
}

/** Records a middleware-level job outcome without ever throwing. */
function safeRecordJob(name: string, success: boolean): void {
  try {
    recordJobExecution(name, 0, success);
  } catch {
    // Metrics emission is best-effort; never let it break the request.
  }
}

/**
 * Read budget for the session lookup on every routed request. Past this the
 * proxy serves the request from the database rather than waiting on Redis.
 */
const SESSION_READ_BUDGET_MS = 150;

/**
 * Server-side redirect validation with canonicalization and allowlist
 *
 * Validates that redirect targets are internal and safe:
 * 1. Decodes URL-encoded redirects to reveal hidden protocols/paths
 * 2. Canonicalizes to prevent bypass techniques (//, \\, etc.)
 * 3. Checks against an allowlist of permitted path patterns
 * 4. Rejects protocol-relative URLs, data URIs, and javascript: URIs
 */
function isValidRedirect(path: string): boolean {
  if (!path) return false;

  // Decode the path to reveal URL-encoded bypass attempts
  try {
    path = decodeURIComponent(path);
  } catch {
    return false;
  }

  // Reject protocol-relative URLs, data URIs, javascript: URIs
  if (
    path.startsWith('//') ||
    path.startsWith('/\\') ||
    path.startsWith('data:') ||
    path.startsWith('javascript:') ||
    path.startsWith('vbscript:')
  ) {
    return false;
  }

  // Must start with a single slash (internal relative path)
  if (!path.startsWith('/')) return false;

  // Allowlist of permitted path patterns
  const allowedPatterns = [
    /^\/$/, // Root
    /^\/login/, // Login page
    /^\/reset-password/, // Password reset
    /^\/update-password/, // Password update
    /^\/drilling(\/|$)/, // Drilling department
    /^\/production(\/|$)/, // Production department
    /^\/plant-processing(\/|$)/, // Plant & Processing department
    /^\/plant-inventory(\/|$)/, // Plant Inventory department
    /^\/access-control(\/|$)/, // Access control department
    /^\/engineering(\/|$)/, // Engineering department
    /^\/control-room(\/|$)/, // Control room department
    /^\/hub/, // Hub
    /^\/admin(\/|$)/, // Admin
    /^\/overview(\/|$)/, // System Overview topology
  ];

  // Check if path matches any allowed pattern
  return allowedPatterns.some((pattern) => pattern.test(path));
}

// DEPARTMENT_ROUTES intentionally excludes '/admin' because admin is a top-level
// restricted route, not a sub-route under (departments). Admin access is handled
// separately via its own auth check in RESTRICTED_ROUTES.
export const DEPARTMENT_ROUTES = [
  'drilling',
  'production',
  'plant-processing',
  'plant-inventory',
  'access-control',
  'engineering',
  'control-room',
];

const RESTRICTED_ROUTES: Record<string, string[]> = {
  'access-control': ['access_control', 'admin', 'supervisor', 'operator'],
  'control-room': ['control_room_operator', 'admin', 'supervisor', 'operator'],
  tools: ['admin', 'supervisor'],
  admin: ['admin'],
};

const PUBLIC_FILE_EXTENSIONS =
  /\.(jpg|jpeg|png|webp|avif|gif|svg|ico|woff|woff2|ttf|otf|eot|mp4|webm|mp3|wav)$/i;

const PUBLIC_ROOT_FILES = new Set([
  '/manifest.json',
  '/manifest.webmanifest',
  '/robots.txt',
  '/sitemap.xml',
  '/browserconfig.xml',
  '/sw.js',
  '/workbox-*.js',
]);

export function normalizeRole(role: unknown): string {
  if (typeof role === 'string') {
    const trimmed = role.trim();
    if (trimmed.length > 0) return trimmed;
  }
  return 'operator';
}

export function isTokenExpiredError(error: unknown): boolean {
  if (!error || typeof error !== 'object' || !('message' in error)) {
    return false;
  }
  const msg = String(error.message);
  return msg.includes('Invalid Refresh Token') || msg.includes('Refresh Token Not Found');
}

function redirectWithError(
  request: NextRequest,
  error: string,
  clientResponse?: NextResponse
): NextResponse {
  const url = new URL('/', request.url);
  url.searchParams.set('error', error);
  const res = NextResponse.redirect(url);
  copyCookies(clientResponse, res);
  return res;
}

async function resolveDeptUuid(
  supabase: MiddlewareClient['supabase'],
  slug: string
): Promise<string | null> {
  const cacheKey = `dept:uuid:${slug}`;
  const cached = await cacheGet<string>(cacheKey);
  if (cached) return cached;

  const { data } = await supabase.from('departments').select('id').eq('name', slug).single();
  if (data?.id) {
    await cacheSet(cacheKey, data.id, 3600); // 1 hour
    return data.id;
  }

  if (slug === 'plant-processing' || slug === 'plant-inventory') {
    const fallbackQuery = supabase.from('departments').select('id').eq('name', 'production');
    const { data: fallbackData } = await (typeof fallbackQuery.maybeSingle === 'function'
      ? fallbackQuery.maybeSingle()
      : fallbackQuery.single());
    if (fallbackData?.id) {
      await cacheSet(cacheKey, fallbackData.id, 3600);
      return fallbackData.id;
    }
  }

  return null;
}

function isPublicBypassPath(pathname: string): boolean {
  if (
    pathname.startsWith('/api/c66') ||
    pathname.startsWith('/api/health') ||
    pathname.startsWith('/api/metrics') ||
    pathname.startsWith('/_vercel/speed-insights') ||
    pathname.startsWith('/_vercel/insights')
  ) {
    return true;
  }

  if (pathname.startsWith('/reset-password') || pathname.startsWith('/update-password')) {
    return true;
  }

  if (PUBLIC_FILE_EXTENSIONS.test(pathname)) {
    return true;
  }

  return PUBLIC_ROOT_FILES.has(pathname) || /^\/workbox-.+\.js$/.test(pathname);
}

function hasSupabaseSessionCookie(request: NextRequest): boolean {
  return (
    request.cookies.has('sb-access-token') ||
    request.cookies
      .getAll()
      .some(
        (c) =>
          (c.name.startsWith('sb-') || c.name.includes('sb-')) && c.name.includes('-auth-token')
      )
  );
}

async function extractClaimsUser(
  client: MiddlewareClient
): Promise<{ user: { id: string } | null; shouldSignOut: boolean }> {
  let user: { id: string } | null = null;
  let shouldSignOut = false;
  try {
    const result = await client.supabase.auth.getClaims();
    const sub = result.data?.claims?.sub;
    user = typeof sub === 'string' && sub.length > 0 ? { id: sub } : null;
    if (result.error && isTokenExpiredError(result.error)) {
      shouldSignOut = true;
    }
  } catch (error) {
    if (isTokenExpiredError(error)) {
      shouldSignOut = true;
    }
  }
  return { user, shouldSignOut };
}

async function handleLoginRoute(request: NextRequest): Promise<NextResponse> {
  if (!hasSupabaseSessionCookie(request)) {
    return NextResponse.next();
  }

  const client = await createMiddlewareClient(request);
  const { user: sessionUser, shouldSignOut } = await extractClaimsUser(client);

  if (shouldSignOut) {
    safeRecordJob('auth.middleware.signout', false);
    await client.supabase.auth.signOut();
    return client.response;
  }

  if (sessionUser) {
    safeRecordJob('auth.middleware.check', true);
    const redirectParam = request.nextUrl.searchParams.get('redirect');
    const target =
      redirectParam && isValidRedirect(redirectParam) && !redirectParam.startsWith('/login')
        ? redirectParam
        : '/hub';
    const redirectRes = NextResponse.redirect(new URL(target, request.url));
    copyCookies(client.response, redirectRes);
    return redirectRes;
  }

  safeRecordJob('auth.middleware.check', false);
  return client.response;
}

async function resolveEmployeeSession(
  client: MiddlewareClient,
  userId: string
): Promise<EmployeeRecord | null> {
  let employee: EmployeeRecord | null = null;
  try {
    employee = await Promise.race([
      readSession(userId),
      new Promise<null>((resolve) => setTimeout(() => resolve(null), SESSION_READ_BUDGET_MS)),
    ]);
  } catch {
    // Redis offline or too slow — fall through to direct DB fetch
    employee = null;
  }

  if (!employee?.id) {
    const { data } = await client.supabase
      .from('employees')
      .select('id, role, department_id, accessible_departments')
      .eq('auth_id', userId)
      .single();
    employee = (data as EmployeeRecord | null) ?? null;
    if (employee) {
      await writeSession({ userId, employee }).catch(() => undefined);
    }
  } else {
    await touchSession(userId).catch(() => undefined);
  }

  return employee;
}

async function enforceRouteAccess(
  request: NextRequest,
  client: MiddlewareClient,
  pathname: string,
  employee: EmployeeRecord | null
): Promise<NextResponse | null> {
  const userRole = normalizeRole(employee?.role);
  const userDept = employee?.department_id ?? null;
  const accessible = employee?.accessible_departments ?? [];

  const pathSegments = pathname.split('/').filter(Boolean);
  const topSegment = pathSegments[0];
  const secondSegment = pathSegments[1];

  // Check restricted top-level routes
  for (const [route, allowedRoles] of Object.entries(RESTRICTED_ROUTES)) {
    if (pathname.startsWith(`/${route}`) && !allowedRoles.includes(userRole)) {
      return redirectWithError(request, 'unauthorized_department', client.response);
    }
  }

  // Also check /{dept}/tools restriction
  if (
    secondSegment === 'tools' &&
    RESTRICTED_ROUTES.tools &&
    !RESTRICTED_ROUTES.tools.includes(userRole)
  ) {
    return redirectWithError(request, 'unauthorized_department', client.response);
  }

  // Check department isolation
  if (topSegment && DEPARTMENT_ROUTES.includes(topSegment)) {
    const isAdmin = userRole === 'admin';

    const deptUuid = await resolveDeptUuid(client.supabase, topSegment);
    if (!deptUuid) {
      return redirectWithError(request, 'unknown_department', client.response);
    }

    const hasAccess = isAdmin || userDept === deptUuid || accessible.includes(deptUuid);
    if (!hasAccess) {
      return redirectWithError(request, 'unauthorized_department', client.response);
    }
  }

  return null;
}

export async function proxy(request: NextRequest): Promise<NextResponse> {
  const pathname = request.nextUrl.pathname;

  if (isPublicBypassPath(pathname)) {
    const res = NextResponse.next();
    // Allow browsers/CDN to serve stale public assets/pages while revalidating,
    // reducing page-switch latency without touching auth-gated routes.
    res.headers.set('Cache-Control', 'public, max-age=60, stale-while-revalidate=300');
    return res;
  }

  if (pathname.startsWith('/login')) {
    return handleLoginRoute(request);
  }

  if (!hasSupabaseSessionCookie(request)) {
    const redirectUrl = new URL('/login', request.url);
    if (isValidRedirect(pathname)) {
      redirectUrl.searchParams.set('redirect', pathname);
    }
    return NextResponse.redirect(redirectUrl);
  }

  const client = await createMiddlewareClient(request);
  let { user, shouldSignOut } = await extractClaimsUser(client);

  if (shouldSignOut) {
    await client.supabase.auth.signOut();
    if (user?.id) {
      const signedOut = user.id;
      await revokeSession(signedOut, { reason: 'logout' }).catch(() => {
        cacheEvictL1ByPrefix(`arch:auth:employee:${signedOut}`);
      });
    }
    user = null;
  }

  if (!user) {
    const redirectUrl = new URL('/login', request.url);
    if (isValidRedirect(pathname)) {
      redirectUrl.searchParams.set('redirect', pathname);
    }
    const redirectResponse = NextResponse.redirect(redirectUrl);
    copyCookies(client.response, redirectResponse);
    return redirectResponse;
  }

  const employee = await resolveEmployeeSession(client, user.id);
  const accessDeniedResponse = await enforceRouteAccess(request, client, pathname, employee);
  if (accessDeniedResponse) {
    return accessDeniedResponse;
  }

  return client.response;
}

export const config = {
  // Exclude static assets and API routes from middleware.
  // API routes handle their own auth; running Supabase getUser() here adds
  // a redundant round-trip (and ~50 s cold-start risk) to every API call.
  matcher: ['/((?!_next/static|_next/image|_vercel|api/|favicon.ico).*)'],
};
