#!/usr/bin/env node
/**
 * Syncs active integration-platform MCP connectors into dev coding-agent
 * configs (.mcp.json, .agents/mcp_config.json, .vscode/mcp.json, and the
 * .junie / .repowise configs when present).
 *
 * Managed entries are prefixed `integration:` and are idempotently replaced on
 * every run; hand-authored server entries are never touched. Secrets are NOT
 * written into the configs — headers reference ${ENV_VAR} placeholders and the
 * values land in a gitignored `.env.integrations` file.
 *
 * Auth: requires INTEGRATIONS_MANIFEST_TOKEN (see GET /api/integrations/manifest)
 * and the portal base URL (NEXT_PUBLIC_APP_URL, default http://localhost:3000).
 *
 * Usage: node scripts/sync-integrations-mcp.mjs
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const REPO_ROOT = path.resolve(__dirname, '..');

const MANAGED_PREFIX = 'integration:';
const INTEGRATIONS_ENV_FILE = path.join(REPO_ROOT, '.env.integrations');

function parseEnvFile(filePath) {
  if (!fs.existsSync(filePath)) return {};
  const env = {};
  for (const line of fs.readFileSync(filePath, 'utf8').split('\n')) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;
    const idx = trimmed.indexOf('=');
    if (idx === -1) continue;
    env[trimmed.slice(0, idx).trim()] = trimmed.slice(idx + 1).trim();
  }
  return env;
}

function stripManagedServers(servers) {
  const kept = {};
  for (const [name, server] of Object.entries(servers ?? {})) {
    if (!name.startsWith(MANAGED_PREFIX)) kept[name] = server;
  }
  return kept;
}

function httpServerEntry(entry) {
  const server = { type: 'http', url: entry.url };
  if (entry.headers && Object.keys(entry.headers).length > 0) {
    server.headers = entry.headers;
  }
  return server;
}

function writeJsonPreserving(filePath, transform) {
  let existing = {};
  if (fs.existsSync(filePath)) {
    try {
      existing = JSON.parse(fs.readFileSync(filePath, 'utf8'));
    } catch {
      console.warn(`Skipping ${filePath} — existing content is not valid JSON`);
      return false;
    }
  }
  const next = transform(existing);
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  fs.writeFileSync(filePath, `${JSON.stringify(next, null, 2)}\n`);
  return true;
}

function writeEnvIntegrations(env) {
  const lines = [
    '# Generated by scripts/sync-integrations-mcp.mjs — do not commit.',
    '# Referenced by ${VAR} placeholders in the managed integration: MCP entries.',
    ...Object.entries(env).map(([key, value]) => `${key}=${value}`),
  ];
  fs.writeFileSync(INTEGRATIONS_ENV_FILE, `${lines.join('\n')}\n`);
}

async function main() {
  const env = {
    ...parseEnvFile(path.join(REPO_ROOT, '.env')),
    ...parseEnvFile(path.join(REPO_ROOT, 'apps/portal/.env')),
    ...process.env,
  };
  const token = env.INTEGRATIONS_MANIFEST_TOKEN;
  if (!token) {
    console.error('INTEGRATIONS_MANIFEST_TOKEN is not set (see .env.example)');
    process.exit(1);
  }
  const baseUrl = (env.NEXT_PUBLIC_APP_URL || 'http://localhost:3000').replace(/\/$/, '');

  let manifest;
  try {
    const response = await fetch(`${baseUrl}/api/integrations/manifest`, {
      headers: { Authorization: `Bearer ${token}` },
    });
    if (!response.ok) {
      throw new Error(`manifest request failed: HTTP ${response.status}`);
    }
    manifest = await response.json();
  } catch (error) {
    console.error(`Failed to fetch integration manifest: ${error.message}`);
    console.error(`Is the portal running at ${baseUrl}?`);
    process.exit(1);
  }

  const slugToEnvRef = {};
  for (const [slug] of Object.entries(manifest.servers)) {
    const envKey = `ARCH_INTEGRATION_${slug.replace(/[^a-zA-Z0-9]/g, '_').toUpperCase()}`;
    slugToEnvRef[slug] = envKey;
  }

  const managedServers = {};
  for (const [slug, entry] of Object.entries(manifest.servers)) {
    managedServers[`${MANAGED_PREFIX}${slug}`] = httpServerEntry(entry);
  }

  // 1. Repo-root .mcp.json (Claude Code and most agents)
  writeJsonPreserving(path.join(REPO_ROOT, '.mcp.json'), (existing) => ({
    ...existing,
    mcpServers: { ...stripManagedServers(existing.mcpServers), ...managedServers },
  }));

  // 2. .agents/mcp_config.json (agents framework; uses serverUrl for HTTP)
  writeJsonPreserving(path.join(REPO_ROOT, '.agents/mcp_config.json'), (existing) => {
    const servers = { ...stripManagedServers(existing.mcpServers) };
    for (const [name, server] of Object.entries(managedServers)) {
      servers[name] = { ...server, serverUrl: server.url };
    }
    return { ...existing, mcpServers: servers };
  });

  // 3. .vscode/mcp.json (uses "servers" key)
  writeJsonPreserving(path.join(REPO_ROOT, '.vscode/mcp.json'), (existing) => ({
    ...existing,
    servers: { ...stripManagedServers(existing.servers), ...managedServers },
  }));

  // 4. Editor-specific configs — only merged when the directory already exists
  for (const configPath of ['.junie/mcp/mcp.json', '.repowise/mcp.json']) {
    const absolute = path.join(REPO_ROOT, configPath);
    if (!fs.existsSync(path.dirname(absolute))) continue;
    writeJsonPreserving(absolute, (existing) => ({
      ...existing,
      mcpServers: { ...stripManagedServers(existing.mcpServers), ...managedServers },
    }));
  }

  // 5. Secrets live in a gitignored env file, referenced via ${VAR}
  writeEnvIntegrations(manifest.env ?? {});
  ensureGitignored();

  const count = Object.keys(managedServers).length;
  console.log(`Synced ${count} integration MCP server(s) into dev agent configs.`);
  console.log(
    `Secrets written to ${path.relative(REPO_ROOT, INTEGRATIONS_ENV_FILE)} (gitignored).`
  );
  if (count > 0) {
    console.log('Restart your coding agents so the new MCP servers are picked up.');
  }
}

function ensureGitignored() {
  const gitignorePath = path.join(REPO_ROOT, '.gitignore');
  if (!fs.existsSync(gitignorePath)) return;
  const content = fs.readFileSync(gitignorePath, 'utf8');
  if (!content.split('\n').includes('.env.integrations')) {
    fs.writeFileSync(gitignorePath, `${content.replace(/\n*$/, '\n')}.env.integrations\n`);
    console.log('Added .env.integrations to .gitignore');
  }
}

main();
